#!/usr/bin/env bash
# Regenerates one note per commit of the Phoenix game repo, with the real diff.
# Run from anywhere:  bash 02-build-steps/code-history/generate-code-history.sh
# Source of truth is git; this script never invents content.
set -euo pipefail

REPO="${1:-$HOME/Workspace/phoenix}"
OUT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FIRST="e900ed7"   # the first Bevy commit; everything before it is the Unreal era

rm -f "$OUT"/Code-*.md

n=0
index=""
while read -r sha; do
  n=$((n+1))
  num=$(printf "%02d" "$n")
  subject=$(git -C "$REPO" log -1 --format=%s "$sha")
  date=$(git -C "$REPO" log -1 --format=%ad --date=short "$sha")
  slug=$(printf '%s' "$subject" | tr 'A-Z' 'a-z' | sed -E -e 's/[^a-z0-9]+/-/g' -e 's/^-+//' -e 's/-+$//' | cut -c1-44 | sed -E 's/-+$//')
  file="Code-$num-$slug.md"
  stat=$(git -C "$REPO" show --stat --format="" "$sha" -- src Cargo.toml | sed '/^$/d')

  {
    echo "---"
    echo "title: \"$num — $subject\""
    echo "date: $date"
    echo "sha: $sha"
    echo "type: code-history"
    echo "tags: [phoenix, code-history, bevy, rust]"
    echo "---"
    echo
    echo "# $num — $subject"
    echo
    echo "\`$sha\` · $date · generated from git, not written by hand."
    echo
    echo "## Files changed"
    echo
    echo '```'
    echo "$stat"
    echo '```'
    echo
    echo "## Diff"
    echo
    echo '```diff'
    git -C "$REPO" show --format="" "$sha" -- src Cargo.toml
    echo '```'
    echo
    echo "## Related"
    echo
    echo "- [[Build-Log]] — what this step was for and what broke"
    echo "- [[Bevy-ECS-Architecture]] — the model these pieces assemble into"
  } > "$OUT/$file"

  index="$index- [[${file%.md}|$num — $subject]] · \`$sha\` · $date"$'\n'
done < <(git -C "$REPO" log --format=%h --reverse "$FIRST^..HEAD")

{
  echo "---"
  echo "title: Code history — every commit, with its diff"
  echo "date: $(date +%Y-%m-%d)"
  echo "type: index"
  echo "tags: [phoenix, code-history]"
  echo "---"
  echo
  echo "# Code history"
  echo
  echo "One note per commit of \`~/Workspace/phoenix\`, each carrying the **real diff** of \`src/\` and"
  echo "\`Cargo.toml\`. Generated by \`generate-code-history.sh\` — re-run it after committing and the"
  echo "notes rebuild from git. Nothing here is written from memory."
  echo
  echo "\`\`\`"
  echo "bash 02-build-steps/code-history/generate-code-history.sh"
  echo "\`\`\`"
  echo
  echo "## Commits"
  echo
  printf '%s' "$index"
  echo
  echo "## Related"
  echo
  echo "- [[Build-Log]] — the narrative: what each step was for, and what went wrong"
  echo "- [[Bevy-ECS-Architecture]] — the model"
  echo "- [[Rust-Keywords-Reference]] — every keyword, with where it appears"
} > "$OUT/00-Code-History.md"

echo "wrote $n notes + index into $OUT"
